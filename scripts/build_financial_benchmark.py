"""Freeze synthetic disclosures, then derive a pilot or complete benchmark from them."""

from __future__ import annotations

import argparse
from decimal import Decimal
from hashlib import sha256
import json
from pathlib import Path
from random import Random


DATA = (Path(__file__).resolve().parents[1] / "src" / "sandboxed_agent_eval_harness"
        / "benchmarks" / "financial_benchmark" / "data")
SEED = 245091
VERSION = "financial-disclosures-v1"
FAMILIES = ("exact_lookup", "entity_period", "unit_conversion", "cross_source", "source_conflict", "insufficient")
FIRST_NAMES = ("Alder", "Briar", "Cairn", "Dovetail", "Ember", "Fallow", "Glimmer", "Harbor", "Ivory", "Juniper")
SECOND_NAMES = ("Creek", "Field", "Gate", "Hill", "Quay")
SUFFIXES = ("Holdings", "Industries")
EXACT_METRICS = ("cash_balance", "inventory_balance", "trade_receivables", "deferred_revenue")
PERIOD_METRICS = ("net_sales", "subscription_revenue", "service_revenue", "product_revenue")
CONVERSION_METRICS = ("research_expense", "lease_payments", "restructuring_expense", "tax_expense")
DIFFERENCE_METRICS = (
    ("cash_from_operations", "capital_spending"), ("capital_spending", "dividend_payments"),
    ("bond_issuance", "debt_repayment"), ("asset_sale_proceeds", "acquisition_spending"),
)
CONFLICT_METRICS = ("adjusted_operating_income", "foreign_exchange_impact", "segment_operating_income", "interest_expense")
MISSING_METRICS = ("backlog_value", "supplier_prepayments", "warranty_reserve", "grant_proceeds")
SOURCE_NAMES = {
    "sec_filing": "annual filing",
    "sec_xbrl_companyfacts": "tagged annual facts",
    "transcript": "earnings call transcript",
    "investor_deck": "investor presentation",
}
MODALITIES = {"sec_filing": "table", "sec_xbrl_companyfacts": "xbrl", "transcript": "transcript", "investor_deck": "table"}
SOURCE_SCALE = {"USD": Decimal(1), "thousands": Decimal(1_000), "millions": Decimal(1_000_000)}
OUTPUT_SCALE = {"usd": Decimal(1), "usd_thousands": Decimal(1_000), "usd_millions": Decimal(1_000_000)}
OUTPUT_NAMES = {"usd": "US dollars", "usd_thousands": "thousands of US dollars", "usd_millions": "millions of US dollars"}


def encoded(data: object) -> bytes:
    return (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def write_frozen(path: Path, value: bytes) -> None:
    if path.exists():
        if path.read_bytes() != value:
            raise ValueError(f"Frozen artifact differs from the generated bytes: {path}")
        return
    path.write_bytes(value)


def decimal_text(value: Decimal) -> str:
    return format(value.normalize(), "f")


def company_groups() -> tuple[list[tuple[str, str, str]], list[str], list[str]]:
    names = []
    for index, (left, right) in enumerate((a, b) for a in FIRST_NAMES for b in SECOND_NAMES):
        names.append(tuple(
            (f"F{index + 1:02d}{letter}", f"{left} {right} {suffix}")
            for letter, suffix in zip("HI", SUFFIXES)
        ))
    split = list(range(len(names)))
    Random(SEED).shuffle(split)
    companies = [(ticker, name, pair[1 - index][0]) for pair in names for index, (ticker, name) in enumerate(pair)]
    development = [ticker for index in split[:10] for ticker, _ in names[index]]
    testing = [ticker for index in split[10:] for ticker, _ in names[index]]
    return companies, development, testing


def make_corpus() -> tuple[dict, dict]:
    companies, development, testing = company_groups()
    rng = Random(SEED)
    documents = []
    for index, (ticker, name, _) in enumerate(companies):
        bucket = index // 2 % len(EXACT_METRICS)
        period = 2022 + (index // 2 * 3 + index // 8) % 4
        exact, period_metric, conversion = EXACT_METRICS[bucket], PERIOD_METRICS[bucket], CONVERSION_METRICS[bucket]
        first, second = DIFFERENCE_METRICS[bucket]
        conflict, missing = CONFLICT_METRICS[bucket], MISSING_METRICS[bucket]

        def add(source: str, year: int, metric: str, amount: Decimal, unit: str) -> None:
            fiscal = f"FY{year}"
            original = f"{ticker}-{source}-{year}"
            value = decimal_text(amount)
            rendered_unit = {"USD": "USD", "millions": "USD millions", "thousands": "USD thousands"}[unit]
            description = SOURCE_NAMES[source]
            words = metric.replace("_", " ")
            lines = (
                f"{name} ({ticker}) {description}, {fiscal}. {words.capitalize()} was {value} {rendered_unit}.",
                f"{description.capitalize()} for {name} ({ticker}) | {fiscal} | {words} | {value} {rendered_unit}.",
                f"{name} ({ticker}) disclosed {value} {rendered_unit} in {words} for {fiscal}. Source: {description}.",
            )
            text = lines[(index + len(metric) + year) % len(lines)]
            evidence_id = "disclosure-" + sha256(f"{original}\n{text}".encode()).hexdigest()[:20]
            documents.append({
                "evidence_id": evidence_id, "document_id": original, "source_group": ticker,
                "company_ticker": ticker, "company_name": name, "fiscal_period": fiscal,
                "source_type": source, "modality": MODALITIES[source], "metric": metric,
                "numeric_value": value, "unit": unit, "currency": "USD", "text": text,
            })

        def amount(low: int = 150, high: int = 9_000) -> Decimal:
            return Decimal(rng.randrange(low, high)) / 4

        add("sec_filing", period, exact, amount(), "millions")
        add("sec_xbrl_companyfacts", period, period_metric, amount() * 1_000, "thousands")
        add("sec_xbrl_companyfacts", period - 1, period_metric, amount() * 1_000, "thousands")
        add("sec_xbrl_companyfacts", period + 1, period_metric, amount() * 1_000, "thousands")
        add("sec_filing", period, conversion, amount() * 1_000, "thousands")
        add("sec_filing", period - 1, conversion, amount() * 1_000, "thousands")
        add("transcript", period, first, amount(), "millions")
        add("investor_deck", period, second, amount() * 1_000, "thousands")
        add("investor_deck", period - 1, second, amount() * 1_000, "thousands")
        value = amount()
        add("sec_filing", period, conflict, value, "millions")
        add("transcript", period, conflict, (value + amount(5, 80)) * 1_000, "thousands")
        add("sec_filing", period - 1, missing, amount(), "millions")

    rng.shuffle(documents)
    return {"version": VERSION, "documents": documents}, {
        "dataset_version": VERSION, "synthetic": True, "seed": SEED,
        "dev_groups": development, "test_groups": testing, "families": list(FAMILIES),
        "company_pair_groups": {ticker: ticker[:-1] for ticker, _, _ in companies},
        "document_count": len(documents), "source_document_count": len({doc["document_id"] for doc in documents}),
    }


def matches(operand: dict, documents: list[dict], allowed: list[str]) -> list[dict]:
    return [doc for doc in documents if (
        doc["company_ticker"] == operand["ticker"] and doc["fiscal_period"] == operand["period"]
        and doc["metric"] == operand["metric"] and doc["source_type"] in allowed
        and ("source_type" not in operand or doc["source_type"] == operand["source_type"])
    )]


def reference(question: dict, documents: list[dict]) -> dict:
    groups = [matches(operand, documents, question["allowed_source_types"]) for operand in question["operands"]]
    values = [{Decimal(doc["numeric_value"]) * SOURCE_SCALE[doc["unit"]] for doc in group} for group in groups]
    answer = None
    evidence = []
    verdict = "insufficient"
    if all(values):
        evidence = [doc["evidence_id"] for group in groups for doc in group]
        if any(len(group) > 1 for group in values):
            verdict = "conflict"
        else:
            verdict = "answer"
            total = next(iter(values[0]))
            if question["operation"] == "difference":
                total -= next(iter(values[1]))
            answer = decimal_text(total / OUTPUT_SCALE[question["unit"]])
    return {
        "task_id": question["task_id"], "verdict": verdict, "answer_value": answer,
        "unit": question["unit"], "evidence_ids": sorted(evidence),
    }


def create_split(groups: list[str], documents: list[dict]) -> tuple[list[dict], list[dict]]:
    questions, labels = [], []
    for index, (ticker, name, other) in enumerate(company_groups()[0]):
        if ticker not in groups:
            continue
        bucket = index // 2 % len(EXACT_METRICS)
        fiscal = f"FY{2022 + (index // 2 * 3 + index // 8) % 4}"
        prior = f"FY{int(fiscal[2:]) - 1}"
        following = f"FY{int(fiscal[2:]) + 1}"
        exact, period_metric, conversion = EXACT_METRICS[bucket], PERIOD_METRICS[bucket], CONVERSION_METRICS[bucket]
        first, second = DIFFERENCE_METRICS[bucket]
        conflict, missing = CONFLICT_METRICS[bucket], MISSING_METRICS[bucket]
        other_name = next(doc["company_name"] for doc in documents if doc["company_ticker"] == other)
        variants = index % 3

        def fact(metric: str, source: str | None = None) -> dict:
            operand = {"ticker": ticker, "period": fiscal, "metric": metric}
            if source is not None:
                operand["source_type"] = source
            return operand

        def lookup(metric: str, unit: str, source: str | None = None) -> str:
            words = metric.replace("_", " ")
            unit_name = OUTPUT_NAMES[unit]
            qualifier = f" in the {SOURCE_NAMES[source]}" if source is not None else ""
            return (
                f"What was {name}'s {fiscal} {words}{qualifier}, in {unit_name}?",
                f"Give {fiscal} {words} for {name}{qualifier}. Report the figure in {unit_name}.",
                f"In {unit_name}, how much {words} did {name} disclose for {fiscal}{qualifier}?",
            )[variants]

        def add(family: str, question: str, operands: list[dict], sources: list[str], unit: str,
                companies: list[str] | None = None, periods: list[str] | None = None) -> None:
            task_id = "financial-" + sha256(f"{ticker}\n{question}".encode()).hexdigest()[:16]
            item = {
                "task_id": task_id, "family": family, "question": question,
                "company_tickers": companies or [ticker], "fiscal_periods": periods or [fiscal],
                "allowed_source_types": sources, "operation": "lookup" if len(operands) == 1 else "difference",
                "operands": operands, "unit": unit,
            }
            label = reference(item, documents)
            expected = {"source_conflict": "conflict", "insufficient": "insufficient"}.get(family, "answer")
            if label["verdict"] != expected or len(label["evidence_ids"]) > 5:
                raise ValueError(f"Unusable reference for {ticker}/{family}: {label}")
            questions.append(item)
            labels.append(label)

        add("exact_lookup", lookup(exact, "usd_millions", "sec_filing"),
            [fact(exact, "sec_filing")], ["sec_filing"], "usd_millions")
        metric_words = period_metric.replace("_", " ")
        disambiguation = (
            f"Use {name}, rather than {other_name}, and {fiscal} rather than {prior}. What was {metric_words} in US dollars?",
            f"What was {name}'s {fiscal} {metric_words} in US dollars? Exclude {other_name}'s figures and {following} figures.",
            f"Resolve the company and period first: {name}, {fiscal}. Report {metric_words} in US dollars, excluding {other_name} and {prior}.",
        )[variants]
        add("entity_period", disambiguation, [fact(period_metric)], ["sec_xbrl_companyfacts"], "usd",
            companies=[ticker, other], periods=[fiscal, prior, following])
        converted_unit = ("usd_millions", "usd")[index // 2 % 2]
        add("unit_conversion", lookup(conversion, converted_unit), [fact(conversion)], ["sec_filing"], converted_unit)
        first_words, second_words = first.replace("_", " "), second.replace("_", " ")
        composition_unit = ("usd", "usd_thousands")[index // 3 % 2]
        unit_name = OUTPUT_NAMES[composition_unit]
        composition = (
            f"For {name} in {fiscal}, subtract {second_words} in the investor presentation from {first_words} in the earnings call. Give the difference in {unit_name}.",
            f"Calculate {name}'s {fiscal} {first_words} minus {second_words}, in {unit_name}. Use the earnings call and investor presentation respectively.",
            f"What is the difference between {name}'s {fiscal} {first_words} in the earnings call and {second_words} in the investor presentation, in {unit_name}? Subtract the latter from the former.",
        )[variants]
        add("cross_source", composition, [fact(first, "transcript"), fact(second, "investor_deck")],
            ["transcript", "investor_deck"], composition_unit)
        add("source_conflict", lookup(conflict, "usd_millions"), [fact(conflict)], ["sec_filing", "transcript"], "usd_millions")
        add("insufficient", lookup(missing, "usd_millions"), [fact(missing)], ["sec_filing", "transcript"], "usd_millions",
            periods=[fiscal, prior])

    return questions, labels


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", required=True, choices=("corpus", "pilot", "full"))
    stage = parser.parse_args().stage
    DATA.mkdir(parents=True, exist_ok=True)
    corpus_path, manifest_path = DATA / "corpus.json", DATA / "manifest.json"
    if stage == "corpus":
        corpus, manifest = make_corpus()
        payload = encoded(corpus)
        manifest["corpus_sha256"] = sha256(payload).hexdigest()
        write_frozen(corpus_path, payload)
        if manifest_path.exists():
            existing = json.loads(manifest_path.read_bytes())
            if any(existing.get(key) != value for key, value in manifest.items()):
                raise ValueError("Frozen corpus manifest differs from the generated metadata")
        else:
            write_frozen(manifest_path, encoded(manifest))
        print(f"corpus_sha256={manifest['corpus_sha256']} documents={len(corpus['documents'])}")
        return

    manifest = json.loads(manifest_path.read_bytes())
    payload = corpus_path.read_bytes()
    if sha256(payload).hexdigest() != manifest["corpus_sha256"]:
        raise ValueError("Frozen corpus checksum mismatch")
    documents = json.loads(payload)["documents"]
    splits = {"dev": manifest["dev_groups"][:4] if stage == "pilot" else manifest["dev_groups"]}
    if stage == "full":
        splits["test"] = manifest["test_groups"]
    artifact_hashes = {}
    for split, groups in splits.items():
        questions, labels = create_split(groups, documents)
        if len(questions) != len(groups) * len(FAMILIES):
            raise ValueError(f"Unexpected {split} task count: {len(questions)}")
        for role, records in (("questions", questions), ("labels", labels)):
            name = f"{split}_{role}.json"
            payload = encoded(records)
            artifact_hashes[name] = sha256(payload).hexdigest()
            path = DATA / name
            if split == "dev" and stage == "full" and "split_sha256" not in manifest and path.exists():
                pilot_records = json.loads(path.read_bytes())
                expanded = {row["task_id"]: row for row in records}
                if len(pilot_records) != 24 or any(expanded.get(row["task_id"]) != row for row in pilot_records):
                    raise ValueError(f"Full development set does not retain its validated pilot: {name}")
                path.write_bytes(payload)
            else:
                write_frozen(path, payload)
        print(f"{split}_questions={len(questions)}")
    if stage == "full":
        previous = manifest.setdefault("split_sha256", artifact_hashes)
        if previous != artifact_hashes:
            raise ValueError("Frozen split hashes differ")
        manifest_path.write_bytes(encoded(manifest))


if __name__ == "__main__":
    main()
